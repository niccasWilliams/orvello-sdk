/**
 * Erzeugt `src/route-index.generated.ts` aus dem vendorierten Vertrag.
 *
 * Warum eine eigene Tabelle, wenn `apiRoutes` dieselbe Auskunft gibt:
 * `apiRoutes` traegt zu jeder der 387 Operationen auch Zusammenfassung,
 * Beschreibung und Tags. Zur Laufzeit braucht der Client davon nichts — er will
 * nur wissen, welche Methode, welcher Pfad und welche Credential-Bahn. Wer die
 * ganze Tabelle einbindet, schleppt rund 200 KB Prosa in jedes Bundle, das den
 * SDK laedt.
 *
 * Die Tabelle wird NICHT von Hand gepflegt und kann deshalb auch nicht veralten:
 * `test/route-index.test.ts` rechnet sie bei jedem `npm run check` aus dem echten
 * `apiRoutes` nach und schlaegt bei der kleinsten Abweichung fehl. Wer eine Route
 * hinzufuegt und dieses Skript vergisst, bekommt rot — nicht eine Route, die
 * still auf der falschen Bahn faehrt.
 *
 * Exakt statt geraten: die Vertragsdateien werden mit esbuild uebersetzt und
 * ausgefuehrt, nicht mit einem regulaeren Ausdruck gelesen. Ein Parser, der die
 * Form der Erzeugung errraet, ist genau die Art von Abhaengigkeit, die beim
 * naechsten Generator-Wechsel unbemerkt bricht.
 */

import { build } from "esbuild";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = join(root, "src/generated/api/index.ts");
const target = join(root, "src/route-index.generated.ts");
const check = process.argv.includes("--check");

const CHANNEL_BY_AUTH_TYPE = { x_api_key_http: "k", x_api_key_https: "k", public: "n" };

async function loadRoutes() {
  const temporary = await mkdtemp(join(tmpdir(), "orvello-route-index-"));
  try {
    const outfile = join(temporary, "routes.mjs");
    await build({ entryPoints: [entry], outfile, bundle: true, format: "esm", platform: "neutral", logLevel: "silent" });
    const module = await import(pathToFileURL(outfile).href);
    return module.apiRoutes;
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
}

function validatedBits(validated) {
  return (validated?.params ? 1 : 0) | (validated?.query ? 2 : 0) | (validated?.body ? 4 : 0);
}

function render(routes) {
  const ids = Object.keys(routes).sort();
  const lines = ids.map((id) => {
    const route = routes[id];
    const authType = route.auth?.type ?? "";
    const channel = CHANNEL_BY_AUTH_TYPE[authType] ?? "b";
    const scopes = route.auth?.scopes?.length ? `, ${JSON.stringify(route.auth.scopes)}` : "";
    return `  ${JSON.stringify(id)}: [${JSON.stringify(route.method.toUpperCase())}, ${JSON.stringify(route.path)}, ${JSON.stringify(channel)}, ${JSON.stringify(authType)}, ${validatedBits(route.meta?.validated)}${scopes}],`;
  });

  return `// GENERATED by scripts/build-route-index.mjs — do not edit by hand.
//
// Die Laufzeit-Tabelle des Vertrags: je Operation nur, was fuer einen Aufruf
// gebraucht wird. Die vollstaendigen Angaben inklusive Beschreibungen stehen
// unveraendert im Unterpfad \`@orvello/sdk/contract\`.
//
// Aufbau je Eintrag:
//   [ HTTP-Methode, Pfad-Vorlage, Bahn, Auth-Art laut Vertrag, Validierungs-Bits, Scopes? ]
//
// Bahn:             "b" = Bearer, "k" = x-api-key, "n" = oeffentlich
// Validierungs-Bits: 1 = params, 2 = query, 4 = body (verodert)
//
// \`test/route-index.test.ts\` rechnet diese Datei bei jedem Lauf aus \`apiRoutes\`
// nach — eine von Hand geaenderte Zeile ueberlebt keinen Testlauf.

export type RouteChannelCode = "b" | "k" | "n";

export type RouteIndexEntry = readonly [
  method: string,
  path: string,
  channel: RouteChannelCode,
  authType: string,
  validated: number,
  scopes?: readonly string[],
];

export const ROUTE_INDEX: Readonly<Record<string, RouteIndexEntry>> = {
${lines.join("\n")}
};
`;
}

const routes = await loadRoutes();
const rendered = render(routes);

if (check) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== rendered) {
    console.error("Route index is stale. Run `npm run build:route-index`.");
    process.exitCode = 1;
  } else {
    console.log(`Route index is current (${Object.keys(routes).length} operations).`);
  }
} else {
  await writeFile(target, rendered);
  console.log(`Wrote route index for ${Object.keys(routes).length} operations.`);
}
