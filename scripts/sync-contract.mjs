import { createHash } from "node:crypto";
import { cp, mkdtemp, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const sourceArg = process.argv.find((value) => value.startsWith("--source="));
const defaultBillRepo = resolve(root, "../node-bill");
const source = resolve(sourceArg?.slice("--source=".length) || process.env.NODE_BILL_REPO || defaultBillRepo, "generated");
const target = resolve(root, "src/generated");

async function filesBelow(directory) {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) continue;
    const path = join(directory, entry.name);
    if (entry.isDirectory()) result.push(...await filesBelow(path));
    else result.push(path);
  }
  return result.sort();
}

async function digest(directory) {
  const hash = createHash("sha256");
  for (const path of await filesBelow(directory)) {
    const relative = path.slice(directory.length + 1);
    hash.update(relative);
    hash.update("\0");
    hash.update(await readFile(path));
    hash.update("\0");
  }
  return hash.digest("hex");
}

for (const required of ["api/index.ts", "api/types.ts", "frontend-types.ts", "openapi.json"]) {
  const info = await stat(join(source, required)).catch(() => null);
  if (!info?.isFile()) throw new Error(`node-bill contract is missing ${required} in ${source}`);
}

const routeFiles = (await filesBelow(join(source, "api"))).filter((path) => basename(path).startsWith("routes.") && path.endsWith(".ts"));
if (routeFiles.length < 10) throw new Error(`Refusing incomplete contract: only ${routeFiles.length} route files found`);

function contractHashModule(sha) {
  return `// GENERATED by scripts/sync-contract.mjs — do not edit by hand.
//
// The fingerprint of the node-bill contract vendored into this package, using
// the same digest as \`sync-contract.mjs\` and as node-bill's own
// \`GET /health/contract\`. Comparing the two answers the only question that
// matters after pinning an SDK version: does the deployment I am calling still
// speak the contract I compiled against?
//
// \`test/diagnose.test.ts\` recomputes this from \`src/generated\` on every
// \`npm run check\`, so a hand-edited contract cannot leave the constant stale.
export const CONTRACT_SHA256 = "${sha}";
`;
}

const sourceDigest = await digest(source);
if (check) {
  const targetDigest = await digest(target);
  if (sourceDigest !== targetDigest) {
    console.error(`Contract drift detected: source=${sourceDigest.slice(0, 12)} package=${targetDigest.slice(0, 12)}`);
    process.exitCode = 1;
  } else {
    console.log(`Contract is current (${sourceDigest.slice(0, 12)}, ${routeFiles.length} route files)`);
  }
} else {
  const temporary = await mkdtemp(join(tmpdir(), "node-bill-sdk-contract-"));
  try {
    await cp(source, temporary, { recursive: true });
    await rm(target, { recursive: true, force: true });
    await cp(temporary, target, { recursive: true });
    await writeFile(join(root, "CONTRACT_SHA256"), `${sourceDigest}\n`);
    await writeFile(join(root, "src/contract-hash.ts"), contractHashModule(sourceDigest));
    console.log(`Synced ${routeFiles.length} route files (${sourceDigest.slice(0, 12)})`);
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
}
